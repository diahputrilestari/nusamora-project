## Kompromi yang bisa dicoba

Tidak semua perbedaan harus dimenangkan salah satu pihak. Beberapa jalan tengah yang sering dipakai pasangan:

- **Menjalankan inti, menyederhanakan bentuk.** Pertahankan makna prosesi, ringkas durasi atau perlengkapannya.
- **Membagi momen.** Satu rangkaian mengikuti tradisi keluarga pihak satu, rangkaian lain mengikuti pihak lainnya.
- **Memadukan.** Elemen dari dua tradisi disatukan secara sadar dan dijelaskan maknanya kepada tamu.
- **Menjelaskan kepada tamu.** Pembawa acara atau buku acara singkat membantu tamu memahami dan menghargai kedua tradisi.
- **Memisahkan acara.** Misalnya akad dan resepsi di tempat dan gaya berbeda, sesuai kebutuhan masing-masing keluarga.

## Soal ekspektasi yang tidak tertulis

Selain tradisi, ada ekspektasi yang jarang diucapkan: siapa yang menanggung biaya, seberapa sering berkunjung, di mana tinggal, kapan punya anak, hingga cara memanggil dan menyapa. Karena tidak diucapkan, ekspektasi ini sering baru muncul sebagai kekecewaan.

- Bicarakan sedini mungkin dan secara konkret, bukan hanya "nanti kita lihat".
- Catat kesepakatan penting dan sampaikan ulang secara tertulis kepada pihak yang terlibat bila perlu, misalnya pembagian biaya atau jadwal acara.
- Siapkan jawaban sopan untuk permintaan yang tidak bisa Anda penuhi: "Terima kasih atas sarannya, kami pertimbangkan dulu ya."

## Jika kebuntuan terjadi

- **Hentikan percakapan saat emosi tinggi.** Sepakati untuk melanjutkannya di hari lain.
- **Libatkan penengah yang dihormati kedua pihak,** misalnya paman, tante, tokoh agama, atau tokoh adat.
- **Fokus pada tujuan bersama:** semua pihak ingin acara berjalan lancar dan pengantin bahagia.
- **Ingat prioritas Anda.** Pernikahan ini tentang hubungan Anda berdua. Menjaga hubungan baik dengan keluarga penting, tetapi tidak dengan mengorbankan kesehatan mental dan kesepakatan Anda sebagai pasangan.

