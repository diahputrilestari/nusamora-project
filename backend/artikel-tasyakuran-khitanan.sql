## Apa itu tasyakuran kelahiran?

Tasyakuran adalah acara syukuran atas kelahiran bayi. Bentuknya beragam: doa bersama, makan bersama, atau berbagi makanan kepada tetangga. Sebagian keluarga menggabungkannya dengan aqiqah, sebagian memisahkannya. Lihat [panduan aqiqah](/artikel/aqiqah-anak-panduan-lengkap-persiapan-acara-dekorasi-undangan) bila Anda ingin mengaitkannya.

