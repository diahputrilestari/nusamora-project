9. **Papan apresiasi** yang diisi sepanjang tahun, lalu dibacakan.
10. **Penghargaan yang ditentukan rekan,** bukan hanya atasan.
11. **Sorotan singkat di rapat besar** untuk tim yang jarang terlihat, seperti dukungan teknis atau administrasi.
12. **Sertifikat atau penghargaan masa kerja** yang dirancang dengan baik.

### Yang bersifat jangka panjang

13. **Kesempatan belajar:** kursus, pelatihan, atau konferensi yang diminati karyawan.
14. **Peran atau proyek baru** yang menunjukkan kepercayaan.
15. **Fleksibilitas kerja** sebagai bentuk apresiasi yang berkelanjutan.

