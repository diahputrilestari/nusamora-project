Alhamdulillah, kami dikaruniai buah hati yang menjadi sumber bahagia kami. Sebagai wujud syukur, kami mengundang keluarga dan sahabat untuk berkumpul dan mendoakan ananda bersama. Semoga kehadiran Anda membawa keberkahan bagi kami semua.

## Contoh santai untuk sahabat

Alhamdulillah, si kecil sudah hadir di tengah kami. Yuk, datang ke acara syukuran aqiqahnya, makan bersama dan bantu kami mendoakan agar ia tumbuh sehat dan saleh/salihah.

## Contoh untuk keluarga besar

Dengan penuh rasa syukur, kami mengabarkan kelahiran ananda. Kami memohon kehadiran dan doa restu Bapak/Ibu sekalian pada acara aqiqah yang akan kami adakan. Atas kehadiran dan doanya, kami ucapkan terima kasih.

## Kalimat penutup yang menyentuh

- "Atas doa dan kehadirannya, kami ucapkan terima kasih."
- "Semoga Allah membalas kebaikan Anda."
- "Kehadiran Anda adalah doa yang paling kami harapkan."

## Tips agar kata-kata terasa tulus

- Gunakan nama yang benar dan sapaan yang pas.
- Hindari kalimat terlalu panjang.
- Sesuaikan nada dengan penerima: formal untuk sepuh, santai untuk sahabat.
- Periksa ejaan dan gelar.
- Tambahkan permintaan doa, bukan hanya ajakan hadir.

