## Tips agar tetap khidmat

- Batasi durasi dan hindari acara yang berlarut.
- Tunjuk MC yang tenang.
- Pastikan pengeras suara tidak terlalu keras demi bayi.
- Sediakan tempat duduk nyaman bagi sepuh.
- Siapkan ruang istirahat untuk ibu dan bayi.

## Mengatur alur tamu

- Tamu datang dan disambut di pintu.
- Tempat salam dan buku tamu di dekat pintu.
- Area makan dipisah dari area acara.
- Paket dibagikan di akhir.

## Peran keluarga

Bagi tugas: penerima tamu, penanggung jawab konsumsi, pemimpin doa, dan dokumentasi. Dengan pembagian jelas, orang tua bisa fokus pada bayi dan doa.

## Menjaga kesehatan bayi dan ibu

Hindari keramaian yang berlebihan. Batasi tamu yang menggendong, dan minta tamu yang sedang sakit untuk tidak hadir dengan sopan.

